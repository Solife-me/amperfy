import Foundation
import Security

/// Stores the provisioned/entered server credentials in the watch Keychain.
/// (App Groups cannot share data between iOS and watchOS, so credentials are
/// delivered via WatchConnectivity and persisted watch-locally here.)
final class WatchCredentialStore {
  static let shared = WatchCredentialStore()

  private let service = "com.amperfy.watch.credentials"
  private let account = "default"

  private init() {}

  func save(_ credentials: WatchCredentials) {
    guard let data = try? JSONEncoder().encode(credentials) else { return }
    let query: [String: Any] = [
      kSecClass as String: kSecClassGenericPassword,
      kSecAttrService as String: service,
      kSecAttrAccount as String: account,
    ]
    SecItemDelete(query as CFDictionary)
    var add = query
    add[kSecValueData as String] = data
    add[kSecAttrAccessible as String] = kSecAttrAccessibleAfterFirstUnlock
    SecItemAdd(add as CFDictionary, nil)
  }

  func load() -> WatchCredentials? {
    let query: [String: Any] = [
      kSecClass as String: kSecClassGenericPassword,
      kSecAttrService as String: service,
      kSecAttrAccount as String: account,
      kSecReturnData as String: true,
      kSecMatchLimit as String: kSecMatchLimitOne,
    ]
    var item: CFTypeRef?
    guard SecItemCopyMatching(query as CFDictionary, &item) == errSecSuccess,
          let data = item as? Data,
          let credentials = try? JSONDecoder().decode(WatchCredentials.self, from: data)
    else { return nil }
    return credentials
  }

  func clear() {
    let query: [String: Any] = [
      kSecClass as String: kSecClassGenericPassword,
      kSecAttrService as String: service,
      kSecAttrAccount as String: account,
    ]
    SecItemDelete(query as CFDictionary)
  }
}
